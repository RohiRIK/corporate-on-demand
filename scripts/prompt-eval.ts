#!/usr/bin/env bun
// prompt-eval.ts — DeepEval wrapper for v1-vs-v2 prompt comparison
// Usage:
//   bun prompt-eval.ts --path <project> --v1 <path> --v2 <path> --test-set <jsonl> --threshold <f>
//
// Returns exit 0 if v2 > v1 + threshold, exit 1 otherwise.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { join, resolve } from "path";
import { parseProjectPath, getArg, hasFlag, ensureDir, isoNow } from "./lib/utils.ts";

if (hasFlag(process.argv, "--help") || process.argv.length <= 2) {
  console.log(`Usage:
  bun prompt-eval.ts --path <project> --v1 <file> --v2 <file> --test-set <jsonl> --threshold <float>

Compares two prompt files against a held-out test set using DeepEval GEval.

Options:
  --path       Path to Corporate-on-Demand project
  --v1         Path to v1 prompt file
  --v2         Path to v2 prompt file
  --test-set   Path to JSONL test cases
  --threshold  Minimum improvement to pass (default 0.05)
  --metric     GEval criteria string (default: "Output is high quality for the task.")
  --judge      Judge model (default: openai/deepseek-chat)
  --help       Show this help

Exit codes:
  0  v2 improves over v1 by at least threshold
  1  v2 does not improve (or regressed)
  2  Error running evaluation
`);
  process.exit(0);
}

const args = process.argv.slice(2);
const projectPath = parseProjectPath(args);
const v1 = getArg(args, "--v1");
const v2 = getArg(args, "--v2");
const testSet = getArg(args, "--test-set");
const threshold = parseFloat(getArg(args, "--threshold") || "0.05");
const metric = getArg(args, "--metric") || "Output is high quality for the task.";
const judge = getArg(args, "--judge") || "openai/deepseek-chat";

if (!v1 || !v2 || !testSet) {
  console.error("Error: --v1, --v2, --test-set are required");
  process.exit(2);
}

const v1Path = resolve(v1);
const v2Path = resolve(v2);
const testSetPath = resolve(testSet);

if (!existsSync(v1Path)) { console.error(`Error: v1 not found: ${v1Path}`); process.exit(2); }
if (!existsSync(v2Path)) { console.error(`Error: v2 not found: ${v2Path}`); process.exit(2); }
if (!existsSync(testSetPath)) { console.error(`Error: test set not found: ${testSetPath}`); process.exit(2); }

const evalPy = `#!/usr/bin/env python3
"""Auto-generated by prompt-eval.ts. Compares v1 and v2 prompts via DeepEval GEval."""
import json
import os
import sys
from pathlib import Path

from deepeval.metrics import GEval
from deepeval.test_case import LLMTestCase, LLMTestCaseParams

V1_PATH = Path("${v1Path}")
V2_PATH = Path("${v2Path}")
TEST_SET = Path("${testSetPath}")
JUDGE_MODEL = os.environ.get("DEEPEVAL_JUDGE_MODEL", "${judge}")
CRITERIA = """${metric.replace(/"/g, '\\"').replace(/\n/g, " ")}"""

def load_prompt(path: Path) -> str:
    return path.read_text()

def load_test_cases(path: Path) -> list[dict]:
    cases = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        cases.append(json.loads(line))
    return cases

def score(prompt_text: str, test_cases: list[dict]) -> float:
    g_eval = GEval(
        name="prompt_comparison",
        criteria=CRITERIA,
        evaluation_params=[LLMTestCaseParams.INPUT, LLMTestCaseParams.ACTUAL_OUTPUT],
    )
    scores = []
    for tc in test_cases:
        # Convention: test case has "input" and "expected_output" fields.
        # We treat the LLM as if it received the test case 'input' field while
        # following prompt_text and produced 'actual_output'. For static-prompt
        # evaluation we use a simple LLM call via the judge model.
        from deepeval.models import DeepEvalBaseLLM
        # Use judge model as the LLM under test
        llm = DeepEvalBaseLLM(model_name=JUDGE_MODEL.split("/")[-1] if "/" in JUDGE_MODEL else JUDGE_MODEL)

        # Build the prompt
        full_prompt = f"{prompt_text}\\n\\n---\\n\\nINPUT:\\n{tc.get('input', '')}"
        actual = llm.generate(full_prompt)

        test_case = LLMTestCase(
            input=tc.get("input", ""),
            actual_output=actual,
            expected_output=tc.get("expected_output"),
        )
        g_eval.measure(test_case)
        scores.append(g_eval.score / 10.0)  # normalize 0-10 → 0-1
    return sum(scores) / max(len(scores), 1)

def main():
    v1_text = load_prompt(V1_PATH)
    v2_text = load_prompt(V2_PATH)
    test_cases = load_test_cases(TEST_SET)
    print(f"Loaded {len(test_cases)} test cases from {TEST_SET}")

    print(f"Scoring v1 ({V1_PATH.name})...")
    v1_score = score(v1_text, test_cases)
    print(f"v1 score: {v1_score:.3f}")

    print(f"Scoring v2 ({V2_PATH.name})...")
    v2_score = score(v2_text, test_cases)
    print(f"v2 score: {v2_score:.3f}")

    improvement = v2_score - v1_score
    threshold = float(os.environ.get("PROMPT_EVAL_THRESHOLD", "0.05"))

    result = {
        "v1_path": str(V1_PATH),
        "v2_path": str(V2_PATH),
        "v1_score": round(v1_score, 4),
        "v2_score": round(v2_score, 4),
        "improvement": round(improvement, 4),
        "threshold": threshold,
        "pass": improvement >= threshold,
        "test_cases": len(test_cases),
        "judge_model": JUDGE_MODEL,
        "timestamp": "${isoNow()}",
    }
    out = Path(os.environ.get("PROMPT_EVAL_OUT", "prompt_eval_result.json"))
    out.write_text(json.dumps(result, indent=2))
    print(f"\\nResult: {json.dumps(result, indent=2)}")

    sys.exit(0 if result["pass"] else 1)

if __name__ == "__main__":
    main()
`;

const tmpDir = join(projectPath, ".prompt-eval");
ensureDir(tmpDir);
const evalPath = join(tmpDir, "compare.py");
writeFileSync(evalPath, evalPy);

const env: Record<string, string> = {
  ...process.env as any,
  DEEPEVAL_JUDGE_MODEL: judge,
  PROMPT_EVAL_THRESHOLD: String(threshold),
  PROMPT_EVAL_OUT: join(tmpDir, "prompt_eval_result.json"),
};

console.log(`Running DeepEval comparison (judge=${judge}, threshold=${threshold})...`);
const proc = Bun.spawn(["uv", "run", "--with", "deepeval", "python", evalPath], {
  cwd: projectPath,
  env,
  stdout: "inherit",
  stderr: "inherit",
});
const exitCode = await proc.exited;

// Read the result
const resultPath = join(tmpDir, "prompt_eval_result.json");
let summary = "";
if (existsSync(resultPath)) {
  const r = JSON.parse(readFileSync(resultPath, "utf-8"));
  const verdict = r.pass ? "RECOMMEND MERGE" : "DO NOT MERGE";
  summary = `V1: ${r.v1_score.toFixed(3)}, V2: ${r.v2_score.toFixed(3)}, improvement: ${r.improvement >= 0 ? "+" : ""}${r.improvement.toFixed(3)}, ${verdict}`;
  console.log(`\n${summary}`);
}
process.exit(exitCode);
